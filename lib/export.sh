#!/usr/bin/env bash
# loopwatch lib — exports (sourced; do not execute).
#   R-15  export_md DIR          each page published this run -> Markdown with front-matter
#   R-16  export_digest DIR      loopwatch-YYYY-MM-DD.md next to Turbo Rig's own digest
# Both read $RUN_DIR/meta-final.json (the pages actually installed this run).

# crude but dependable HTML -> Markdown for loopwatch's own page skeleton.
# Done in jq (Oniguruma) rather than sed so GNU and BSD behave identically.
html_to_md() {
  jq -Rrs '
    gsub("\r"; "")
    | (capture("(?s)<main>(?<m>.*)</main>").m // .)
    | gsub("(?s)<footer>.*?</footer>"; "")
    | gsub("(?s)<div class=\"meta\">.*?</div>"; "")
    | gsub("(?s)<pre><code[^>]*>"; "\n```\n") | gsub("(?s)</code></pre>"; "\n```\n")
    | gsub("<h1[^>]*>"; "\n# ") | gsub("<h2[^>]*>"; "\n## ") | gsub("<h3[^>]*>"; "\n### ")
    | gsub("</h[1-6]>"; "\n")
    | gsub("<li[^>]*>"; "\n- ") | gsub("</li>"; "")
    | gsub("<p[^>]*>"; "\n") | gsub("</p>"; "\n") | gsub("<br[^>]*>"; "\n")
    | gsub("</?code>"; "`") | gsub("</?strong>"; "**") | gsub("</?em>"; "_")
    | gsub("(?s)<[^>]*>"; "")
    | gsub("&lt;"; "<") | gsub("&gt;"; ">") | gsub("&quot;"; "\"") | gsub("&#39;"; "\u0027") | gsub("&amp;"; "&")
    | gsub("\n[ \t]+\n"; "\n\n") | gsub("\n{3,}"; "\n\n")
    | sub("^\\s+"; "")' "$1"
}

export_md() {
  local dir="$1" slug path title
  mkdir -p "$dir"
  while IFS=$'\t' read -r slug path; do
    [[ -n "$slug" && -f "$SITE_DIR/$path" ]] || continue
    title="$(jq -r --arg s "$slug" '.pages[] | select(.slug == $s) | .title' "$RUN_DIR/meta-final.json")"
    {
      echo "---"
      jq -r --arg s "$slug" '.pages[] | select(.slug == $s)
        | "slug: " + .slug,
          "title: " + (.title | tojson),
          "category: " + .category,
          "tags: " + ((.tags // []) | tojson),
          "date: " + .date,
          "source: " + ((.source // "") | tojson),
          "summary: " + (.summary | tojson),
          "catalog_path: " + .path' "$RUN_DIR/meta-final.json"
      echo "generator: loopwatch"
      echo "---"
      echo
      html_to_md "$SITE_DIR/$path"
    } > "$dir/$slug.md"
    log "export-md: $dir/$slug.md (${title})"
  done < <(jq -r '.pages[] | [.slug, .path] | @tsv' "$RUN_DIR/meta-final.json")
}

export_digest() {
  local dir="$1" out
  mkdir -p "$dir"
  out="$dir/loopwatch-$RUN_DATE.md"
  jq -r --arg date "$RUN_DATE" --arg cost "$(usage_cost)" --arg pr "${CATALOG_PR_URL:-}" '
    "# loopwatch digest — " + $date, "",
    .digest_summary, "",
    (if (.highlights // []) | length > 0 then "## Highlights", "", ((.highlights // [])[] | "- " + .), "" else empty end),
    "## Pages", "",
    (if (.pages | length) == 0 then "_None: nothing cleared the reference bar._" else (.pages[] | "- **" + .title + "** (`" + .category + "`) — " + .summary + " → `" + .path + "`") end),
    "",
    "<sub>model cost: $" + $cost + (if $pr != "" then " · PR: " + $pr else "" end) + " · generated by loopwatch</sub>"
  ' "$RUN_DIR/meta-final.json" > "$out"
  log "digest exported: $out"
}
