#!/usr/bin/env bash
# loopwatch end-to-end smoke test — stubbed claude CLI, fixture transcript + git repo.
# No network, no real transcripts touched. Asserts the full collect -> extract -> publish path.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/loopwatch-test.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }
ok() { echo "  ok: $*"; }

# ── test repo with the scaffold inside ──────────────────────────────────
REPO="$WORK/repo"
mkdir -p "$REPO"
git -C "$REPO" init -q -b main 2>/dev/null || git -C "$REPO" init -q
git -C "$REPO" config user.email "test@test"
git -C "$REPO" config user.name  "loopwatch-test"
cp -R "$SRC_ROOT" "$REPO/loopwatch"
rm -rf "$REPO/loopwatch/.git" "$REPO/loopwatch/state"
mkdir -p "$REPO/loopwatch/state"
git -C "$REPO" add -A
git -C "$REPO" commit -qm "init"
LW="$REPO/loopwatch"

# ── fixture transcript (with a planted fake secret for the scrubber) ────
FIX="$WORK/fixtures"
mkdir -p "$FIX"
cat > "$FIX/session1.jsonl" <<'EOF'
{"type":"user","message":{"role":"user","content":"We decided to move Turbo-Flow ingest to a K8s CronJob plus work queue. Token for later: ghp_abcdefghijklmnopqrstuvwxyz123456"}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Agreed. CronJob plus queue decouples schedule from execution. Tradeoff: at-least-once delivery, so the worker must be idempotent."}]}}
{"type":"system","message":{"role":"system","content":"tool noise that must be filtered out"}}
EOF

# ── fixture git source repo ─────────────────────────────────────────────
SRCREPO="$WORK/srcrepo"
mkdir -p "$SRCREPO"
git -C "$SRCREPO" init -q -b main 2>/dev/null || git -C "$SRCREPO" init -q
git -C "$SRCREPO" config user.email "test@test"
git -C "$SRCREPO" config user.name  "loopwatch-test"
echo "fn main() {}" > "$SRCREPO/main.rs"
git -C "$SRCREPO" add -A
git -C "$SRCREPO" commit -qm "feat: initial ingest worker"

# ── stub claude CLI (emulates the extraction output contract) ───────────
cat > "$WORK/fake-claude" <<'EOF'
#!/usr/bin/env bash
# stub extraction stage: ignores args/stdin, writes contract-conformant output to cwd
mkdir -p pages
cat > pages/k8s-cronjob-queue-ingest.html <<'HTML'
<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Turbo-Flow ingest: CronJob + work queue</title>
<style>body{background:#0f1115;color:#d7dae0}</style></head>
<body><main><h1>Turbo-Flow ingest: CronJob + work queue</h1>
<div class="meta">test</div><p>Decision: CronJob + queue; worker must be idempotent.</p>
<footer>generated by loopwatch</footer></main></body></html>
HTML
cat > run-meta.json <<'JSON'
{
  "run_date": "TEST",
  "digest_summary": "Settled the Turbo-Flow ingest architecture: K8s CronJob feeding a work queue, idempotent worker.",
  "highlights": ["ingest architecture decided", "one commit in srcrepo"],
  "pages": [
    {
      "file": "pages/k8s-cronjob-queue-ingest.html",
      "slug": "k8s-cronjob-queue-ingest",
      "title": "Turbo-Flow ingest: CronJob + work queue",
      "category": "infra/kubernetes",
      "tags": ["k8s", "turbo-flow"],
      "summary": "CronJob + work queue for ingest; at-least-once semantics require idempotent workers.",
      "source": "claude-code:turbo-flow"
    }
  ]
}
JSON
EOF
chmod +x "$WORK/fake-claude"

# ── config ──────────────────────────────────────────────────────────────
cat > "$LW/loopwatch.conf" <<EOF
CLAUDE_CODE_GLOBS=("$FIX/*.jsonl")
COWORK_GLOBS=()
GIT_REPOS=("$SRCREPO")
CLAUDE_BIN="$WORK/fake-claude"
PULL=false
PUSH=false
EOF

YEAR="$(date +%Y)"
TODAY="$(date +%F)"

echo "— run 1: full pipeline —"
"$LW/bin/loopwatch-run.sh"

test -f "$LW/site/pages/$YEAR/k8s-cronjob-queue-ingest.html" || fail "page not installed"
ok "page installed"
jq -e '.entries | length == 1' "$LW/site/manifest.json" >/dev/null || fail "manifest entry missing"
jq -e '.digests | length == 1' "$LW/site/manifest.json" >/dev/null || fail "digest record missing"
ok "manifest updated (1 entry, 1 digest)"
test -f "$LW/site/digests/$TODAY.html" || fail "digest page missing"
grep -q "k8s-cronjob-queue-ingest" "$LW/site/digests/$TODAY.html" || fail "digest doesn't link the page"
ok "digest page written and links the new page"
[[ "$(git -C "$REPO" rev-list --count HEAD)" == "2" ]] || fail "expected 2 commits (init + loopwatch)"
ok "publish commit created"
jq -e '.files | length == 1' "$LW/state/watermarks.json" >/dev/null || fail "file watermark not saved"
jq -e '.git | length == 1' "$LW/state/watermarks.json" >/dev/null || fail "git watermark not saved"
ok "watermarks advanced"
if grep -rq "ghp_abcdefghijklmnopqrstuvwxyz123456" "$LW/site" "$LW/state"; then
  fail "planted secret leaked past the scrubber"
fi
ok "planted secret scrubbed"

echo "— run 2: no new activity -> skip —"
"$LW/bin/loopwatch-run.sh"
[[ "$(git -C "$REPO" rev-list --count HEAD)" == "2" ]] || fail "empty run should not commit"
ok "empty run skipped cleanly"

echo "— run 3: new delta + duplicate slug -> dry-run then dedup —"
cat >> "$FIX/session1.jsonl" <<'EOF'
{"type":"user","message":{"role":"user","content":"Follow-up on the ingest work: pin the CronJob to the spot node pool, add a PodDisruptionBudget, and set activeDeadlineSeconds so a wedged worker cannot hold the queue. Also decided to expose queue depth as a Prometheus gauge so HPA can scale the workers on backlog instead of CPU."}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Captured. Spot pool + PDB is the right cost/safety balance for batch ingest. Scaling on queue depth via external metrics is much better than CPU for this shape of workload; remember the stabilization window so it does not flap. activeDeadlineSeconds plus the idempotent worker gives you clean crash semantics end to end."}]}}
EOF
"$LW/bin/loopwatch-run.sh" --dry-run
[[ "$(git -C "$REPO" rev-list --count HEAD)" == "2" ]] || fail "dry-run must not commit"
jq -e '.entries | length == 1' "$LW/site/manifest.json" >/dev/null || fail "dry-run must not touch manifest"
ok "dry-run is side-effect free"
"$LW/bin/loopwatch-run.sh"
jq -e '.entries | length == 1' "$LW/site/manifest.json" >/dev/null || fail "duplicate slug was not deduped"
jq -e '.digests | length == 2' "$LW/site/manifest.json" >/dev/null || fail "second digest missing"
ok "duplicate slug deduped, digest still recorded"

echo
echo "PASS — all smoke checks green"
