#!/usr/bin/env bash
# loopwatch-discover.sh — Phase 0 discovery, READ-ONLY. Run on the Mac that holds the transcripts.
# Prints a Markdown report to stdout: CLI capabilities, transcript roots, schema histogram
# (keys/types only — never message content), self-ingestion evidence, catalog deployment hints.
# Project directory names can reveal client names, so they are hashed unless --show-names.
# usage: loopwatch-discover.sh [--show-names] > revival-findings.md
set -uo pipefail

SHOW_NAMES=false
[[ "${1:-}" == "--show-names" ]] && SHOW_NAMES=true

CLAUDE_BIN="${CLAUDE_BIN:-claude}"
CC_ROOT="${CLAUDE_CODE_ROOT:-$HOME/.claude/projects}"
COWORK_ROOT="${COWORK_ROOT:-$HOME/Library/Application Support/Claude}"

hash8() {
  if command -v shasum >/dev/null 2>&1; then printf '%s' "$1" | shasum -a 256 | cut -c1-8
  else printf '%s' "$1" | sha256sum | cut -c1-8; fi
}
label() { if [[ "$SHOW_NAMES" == "true" ]]; then printf '%s' "$1"; else printf 'dir-%s' "$(hash8 "$1")"; fi; }
mtime() { stat -c %Y "$1" 2>/dev/null || stat -f %m "$1" 2>/dev/null || echo 0; }

echo "# loopwatch discovery — $(date '+%Y-%m-%d %H:%M %Z') on $(uname -sm)"
echo

echo "## 1. claude CLI"
if command -v "$CLAUDE_BIN" >/dev/null 2>&1; then
  echo "- path: \`$(command -v "$CLAUDE_BIN")\`"
  echo "- version: \`$("$CLAUDE_BIN" --version 2>/dev/null | head -1)\`"
  help="$("$CLAUDE_BIN" --help 2>/dev/null)"
  for fl in --no-session-persistence --max-budget-usd --output-format --strict-mcp-config --max-turns; do
    if printf '%s' "$help" | grep -q -- "$fl"; then echo "- \`$fl\`: listed in --help"
    else echo "- \`$fl\`: not listed in --help (may still be accepted as a hidden flag)"; fi
  done
else
  echo "- NOT FOUND on PATH (set CLAUDE_BIN)"
fi
echo

echo "## 2. Claude Code transcripts ($CC_ROOT)"
if [[ -d "$CC_ROOT" ]]; then
  n_dirs=0; n_files=0; bytes=0; recent=0; now="$(date +%s)"
  for d in "$CC_ROOT"/*/; do
    [[ -d "$d" ]] || continue
    n_dirs=$((n_dirs + 1))
    for f in "$d"*.jsonl; do
      [[ -f "$f" ]] || continue
      n_files=$((n_files + 1))
      bytes=$((bytes + $(wc -c < "$f" | tr -d ' ')))
      if [[ $((now - $(mtime "$f"))) -lt 172800 ]]; then recent=$((recent + 1)); fi
    done
  done
  echo "- project dirs: $n_dirs · jsonl files: $n_files · total: $((bytes / 1024)) KB · touched in last 48h: $recent"
  echo "- project dirs modified in the last 7 days (name → files, KB):"
  for d in "$CC_ROOT"/*/; do
    [[ -d "$d" ]] || continue
    [[ $((now - $(mtime "$d"))) -lt 604800 ]] || continue
    kb="$(du -sk "$d" 2>/dev/null | awk '{print $1}')"
    nf="$(find "$d" -maxdepth 1 -name '*.jsonl' | wc -l | tr -d ' ')"
    echo "  - \`$(label "$(basename "$d")")\` → $nf files, ${kb} KB"
  done
else
  echo "- directory does not exist"
fi
echo

echo "## 3. Self-ingestion evidence (bug 1)"
echo "Project dirs created by loopwatch's own headless runs (v0.1 ran from \$TMPDIR/loopwatch.XXXXXX; v0.2 runs from ~/.local/state/loopwatch/run):"
found=0
for d in "$CC_ROOT"/*loopwatch*/; do
  [[ -d "$d" ]] || continue
  found=1
  echo "- \`$(basename "$d")\` — $(find "$d" -name '*.jsonl' | wc -l | tr -d ' ') transcript(s), $(du -sk "$d" | awk '{print $1}') KB"
done
[[ "$found" -eq 1 ]] || echo "- none found (either v0.1 never ran on this machine, or its dirs were cleaned)"
echo

echo "## 4. Cowork transcripts ($COWORK_ROOT)"
if [[ -d "$COWORK_ROOT" ]]; then
  echo "- jsonl files under it (path shape with names hashed, depth ≤ 6):"
  find "$COWORK_ROOT" -maxdepth 6 -name '*.jsonl' -type f 2>/dev/null | head -400 \
    | sed "s|^$COWORK_ROOT/||" | awk -F/ '{ s=$1; for (i=2;i<NF;i++) s=s"/*"; print s"/*.jsonl" }' \
    | sort | uniq -c | sort -rn | head -10 | sed 's/^/  - /'
  newest="$(find "$COWORK_ROOT" -maxdepth 6 -name '*.jsonl' -type f 2>/dev/null | while IFS= read -r f; do printf '%s\t%s\n' "$(mtime "$f")" "$f"; done | sort -rn | head -1 | cut -f2-)"
  if [[ -n "$newest" ]]; then
    echo "- newest file schema histogram (type · role · content shape · keys — no content):"
    jq -c '{type, role: (.message.role // null), content: (.message.content | type), parts: ((.message.content | arrays | map(.type)) // null)}' "$newest" 2>/dev/null \
      | sort | uniq -c | sort -rn | head -15 | sed 's/^/  - /'
    echo "- top-level keys seen:"
    jq -r 'keys[]' "$newest" 2>/dev/null | sort | uniq -c | sort -rn | head -25 | awk '{printf "  - %s (%s)\n", $2, $1}'
  fi
else
  echo "- directory does not exist"
fi
echo

echo "## 5. Existing catalog deployment"
echo "- v0.1 wrote \`generated by loopwatch\` into every page footer. Search your HTML repos for that string, e.g.:"
echo "  \`gh search code '\"generated by loopwatch\"' --owner marcuspat --owner adventurewave-labs --owner creandotumatrix-labs\`"
if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1; then
  for o in marcuspat adventurewave-labs creandotumatrix-labs; do
    hits="$(gh search code '"generated by loopwatch"' --owner "$o" --json repository -q '.[].repository.nameWithOwner' 2>/dev/null | sort -u | tr '\n' ' ')"
    echo "  - $o: ${hits:-no hits}"
  done
fi
